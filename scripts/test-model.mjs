import assert from 'node:assert/strict';
import {dateRange,todayVienna,inView,icsForTask} from '../lib/model.ts';
import {parseImport} from '../lib/import.ts';
assert.equal(todayVienna(new Date('2026-10-25T23:30:00Z')),'2026-10-26');
assert.deepEqual(dateRange('week','2026-10-26'),['2026-10-26','2026-11-01']);
assert.deepEqual(dateRange('next-week','2026-10-26'),['2026-11-02','2026-11-08']);
assert.deepEqual(dateRange('month','2026-12-31'),['2026-12-01','2026-12-31']);
assert.deepEqual(dateRange('week','2027-01-03'),['2026-12-28','2027-01-03']);
assert.equal(inView({dueDate:'2026-10-25'},'today','2026-10-26'),true);
assert.equal(inView({dueDate:null},'today','2026-10-26'),false);
const source='# Projekt Garten\n- [ ] Hochbeet planen\n- [ ] Saatgut kaufen\n\n# Einkauf\n- [ ] Kaffee kaufen\n- [ ] Papier besorgen';
const imported=parseImport(source);
assert.equal(imported.lists.length,2);assert.equal(imported.tasks.length,4);
const chosen=imported.lists.filter(l=>l.name==='Projekt Garten');
const selected=imported.tasks.filter(t=>chosen.some(l=>l.id===t.listId));assert.deepEqual(selected.map(t=>t.title),['Hochbeet planen','Saatgut kaufen']);
assert.deepEqual(parseImport(source),imported);
assert.deepEqual(parseImport(JSON.stringify(imported)),imported);
const csv=parseImport('list,title,notes,done\nEinkauf,"Kaffee, gemahlen","Notiz\nmit Umbruch",true','test.csv');assert.equal(csv.tasks[0].notes,'Notiz\nmit Umbruch');assert.equal(csv.tasks[0].done,true);
const ics=icsForTask({id:'test',title:'Ein Titel; mit Komma,\nund Zeile',notes:'ä'.repeat(100),dueDate:null,reminderAt:'2026-10-27T08:00:00Z',updatedAt:'2026-10-26T12:00:00Z'});
assert.match(ics,/TRIGGER;VALUE=DATE-TIME:20261027T080000Z/);assert.match(ics,/SUMMARY:Ein Titel\\; mit Komma\\,\\nund Zeile/);assert.ok(ics.split('\r\n').every(l=>Buffer.byteLength(l)<=75));
console.log('PASS: Vienna dates, week/month boundaries, single-record views, selected fictional import, repeat import IDs, CSV, JSON roundtrip, calendar alarms.');
